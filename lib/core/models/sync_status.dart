/// حالة المزامنة (Sync Status)
///
/// تستخدم لتتبع حالة السجلات بين قاعدة البيانات المحلية والسيرفر.
enum SyncStatus {
  /// تمت المزامنة بنجاح
  synced,

  /// بانتظار الرفع إلى السيرفر (تم التعديل محلياً)
  pendingPush,

  /// بانتظار التحميل من السيرفر (تم التعديل في السيرفر)
  pendingPull,

  /// يوجد تعارض في البيانات
  conflict,
}
