/// أيقونة مخصصة مع تأثيرات
///
/// widget يعرض أيقونة مع إمكانية إضافة تأثيرات وألوان مخصصة
class CustomIcon extends StatelessWidget {
  /// إنشاء أيقونة مخصصة
  const CustomIcon({
    required this.icon,
    super.key,
    this.size,
    this.color,
    this.badge,
    this.badgeColor,
    this.onTap,
  });

  /// الأيقونة
  final IconData icon;

  /// حجم الأيقونة
  final double? size;

  /// لون الأيقونة
  final Color? color;

  /// نص الشارة (badge)
  final String? badge;

  /// لون الشارة
  final Color? badgeColor;

  /// عند النقر
  final VoidCallback? onTap;

  @override
  Widget build(BuildContext context) {
    final iconWidget = Icon(icon, size: size, color: color);

    if (badge != null) {
      return InkWell(
        onTap: onTap,
        borderRadius: BorderRadius.circular(24),
        child: Stack(
          clipBehavior: Clip.none,
          children: [
            iconWidget,
            Positioned(
              right: -4,
              top: -4,
              child: Container(
                padding: const EdgeInsets.all(4),
                decoration: BoxDecoration(
                  color: badgeColor ?? Colors.red,
                  shape: BoxShape.circle,
                ),
                constraints: const BoxConstraints(minWidth: 16, minHeight: 16),
                child: Text(
                  badge!,
                  style: const TextStyle(
                    color: Colors.white,
                    fontSize: 10,
                    fontWeight: FontWeight.bold,
                  ),
                  textAlign: TextAlign.center,
                ),
              ),
            ),
          ],
        ),
      );
    }

    if (onTap != null) {
      return InkWell(
        onTap: onTap,
        borderRadius: BorderRadius.circular(24),
        child: iconWidget,
      );
    }

    return iconWidget;
  }
}

/// أيقونة متحركة
///
/// widget يعرض أيقونة مع تأثير حركي
class AnimatedIcon extends StatefulWidget {
  /// إنشاء أيقونة متحركة
  const AnimatedIcon({
    required this.icon,
    super.key,
    this.size,
    this.color,
    this.duration = const Duration(milliseconds: 300),
  });

  /// الأيقونة
  final IconData icon;

  /// حجم الأيقونة
  final double? size;

  /// لون الأيقونة
  final Color? color;

  /// مدة الحركة
  final Duration duration;

  @override
  State<AnimatedIcon> createState() => _AnimatedIconState();
}

class _AnimatedIconState extends State<AnimatedIcon>
    with SingleTickerProviderStateMixin {
  late AnimationController _controller;
  late Animation<double> _scaleAnimation;

  @override
  void initState() {
    super.initState();
    _controller = AnimationController(duration: widget.duration, vsync: this);
    _scaleAnimation = Tween<double>(
      begin: 0.8,
      end: 1,
    ).animate(CurvedAnimation(parent: _controller, curve: Curves.easeOut));
    // تشغيل الأنيميشن (fire-and-forget pattern)
    _controller.forward().ignore();
  }

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) => ScaleTransition(
    scale: _scaleAnimation,
    child: Icon(widget.icon, size: widget.size, color: widget.color),
  );
}
