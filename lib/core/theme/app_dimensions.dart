/// نظام الأبعاد الموحد لتطبيق بصير
///
/// يوفر هذا الملف جميع الأبعاد والمسافات المستخدمة في التطبيق
/// بما يتوافق مع معايير إمكانية الوصول WCAG 2.1 Level AA.
///
/// **المعايير المطبقة:**
/// - مساحة النقر الدنيا: 48x48px (WCAG 2.5.5)
/// - أحجام الأيقونات: 24px (أساسي)
/// - أحجام الأزرار: 48px (ارتفاع)
/// - المسافات: نظام 8px grid
///
/// **الاستخدام:**
/// ```dart
/// Container(
///   height: AppDimensions.buttonHeight,
///   padding: EdgeInsets.all(AppDimensions.paddingMedium),
///   child: Icon(
///     Icons.add,
///     size: AppDimensions.iconMedium,
///   ),
/// )
/// ```
library;

/// نظام الأبعاد الموحد
class AppDimensions {
  AppDimensions._();

  // ============================================================================
  // أحجام الأيقونات (Icon Sizes)
  // ============================================================================

  /// حجم الأيقونة الصغيرة (16px)
  ///
  /// **الاستخدام:** أيقونات ثانوية، شارات، مؤشرات
  static const double iconSmall = 16.0;

  /// حجم الأيقونة المتوسطة (24px) - الحجم الأساسي
  ///
  /// **الاستخدام:** معظم الأيقونات في التطبيق
  /// **المعيار:** WCAG 2.5.5 - حجم مناسب للنقر
  static const double iconMedium = 24.0;

  /// حجم الأيقونة الكبيرة (32px)
  ///
  /// **الاستخدام:** أيقونات رئيسية، أيقونات الحالات الفارغة
  static const double iconLarge = 32.0;

  /// حجم الأيقونة الكبيرة جداً (48px)
  ///
  /// **الاستخدام:** أيقونات الصفحات الرئيسية، شعارات
  static const double iconXLarge = 48.0;

  // ============================================================================
  // أحجام الأزرار (Button Sizes)
  // ============================================================================

  /// ارتفاع الزر الأساسي (48px)
  ///
  /// **المعيار:** WCAG 2.5.5 - مساحة نقر لا تقل عن 48x48px
  static const double buttonHeight = 48.0;

  /// الحد الأدنى لعرض الزر (120px)
  ///
  /// **الاستخدام:** يضمن مساحة كافية للنص والأيقونة
  static const double buttonMinWidth = 120.0;

  /// نصف قطر حواف الزر (8px)
  ///
  /// **الاستخدام:** حواف مستديرة بشكل معتدل
  static const double buttonBorderRadius = 8.0;

  /// ارتفاع الزر الصغير (40px)
  ///
  /// **الاستخدام:** أزرار ثانوية، أزرار في البطاقات
  /// **ملاحظة:** أقل من المعيار، استخدم بحذر
  static const double buttonHeightSmall = 40.0;

  /// ارتفاع الزر الكبير (56px)
  ///
  /// **الاستخدام:** أزرار رئيسية، أزرار الإجراءات الأساسية
  static const double buttonHeightLarge = 56.0;

  // ============================================================================
  // أحجام حقول الإدخال (Input Field Sizes)
  // ============================================================================

  /// ارتفاع حقل الإدخال (48px)
  ///
  /// **المعيار:** WCAG 2.5.5 - مساحة نقر كافية
  static const double inputHeight = 48.0;

  /// سمك حدود حقل الإدخال في الحالة العادية (1px)
  ///
  /// **الاستخدام:** حدود واضحة في الحالة العادية
  static const double inputBorderWidth = 1.0;

  /// سمك حدود حقل الإدخال في حالة التركيز (2px)
  ///
  /// **الاستخدام:** حدود أكثر وضوحاً عند التركيز
  static const double inputBorderWidthFocused = 2.0;

  /// نصف قطر حواف حقل الإدخال (8px)
  ///
  /// **الاستخدام:** حواف مستديرة بشكل معتدل
  static const double inputBorderRadius = 8.0;

  // ============================================================================
  // أحجام البطاقات (Card Sizes)
  // ============================================================================

  /// نصف قطر حواف البطاقة (12px)
  ///
  /// **الاستخدام:** حواف مستديرة للبطاقات
  static const double cardBorderRadius = 12.0;

  /// سمك حدود البطاقة (1px)
  ///
  /// **الاستخدام:** حدود واضحة للبطاقات
  static const double cardBorderWidth = 1.0;

  /// ارتفاع ظل البطاقة (2px)
  ///
  /// **الاستخدام:** ظل خفيف للبطاقات
  static const double cardElevation = 2.0;

  // ============================================================================
  // المسافات (Spacing)
  // ============================================================================
  // نظام 8px grid للمسافات المتسقة

  /// مسافة صغيرة جداً (4px)
  ///
  /// **الاستخدام:** مسافات دقيقة بين العناصر المتقاربة
  static const double spacingXSmall = 4.0;

  /// مسافة صغيرة (8px) - الوحدة الأساسية
  ///
  /// **الاستخدام:** مسافات بين العناصر المتقاربة
  static const double spacingSmall = 8.0;

  /// مسافة متوسطة (16px)
  ///
  /// **الاستخدام:** مسافات بين العناصر في نفس المجموعة
  static const double spacingMedium = 16.0;

  /// مسافة كبيرة (24px)
  ///
  /// **الاستخدام:** مسافات بين المجموعات المختلفة
  static const double spacingLarge = 24.0;

  /// مسافة كبيرة جداً (32px)
  ///
  /// **الاستخدام:** مسافات بين الأقسام الرئيسية
  static const double spacingXLarge = 32.0;

  /// مسافة كبيرة جداً جداً (48px)
  ///
  /// **الاستخدام:** مسافات بين الصفحات أو الأقسام الكبيرة
  static const double spacingXXLarge = 48.0;

  // ============================================================================
  // الحشو (Padding)
  // ============================================================================

  /// حشو صغير جداً (4px)
  static const double paddingXSmall = spacingXSmall;

  /// حشو صغير (8px)
  static const double paddingSmall = spacingSmall;

  /// حشو متوسط (16px) - الحشو الأساسي
  static const double paddingMedium = spacingMedium;

  /// حشو كبير (24px)
  static const double paddingLarge = spacingLarge;

  /// حشو كبير جداً (32px)
  static const double paddingXLarge = spacingXLarge;

  // ============================================================================
  // مساحة النقر (Touch Target)
  // ============================================================================

  /// الحد الأدنى لمساحة النقر (48px)
  ///
  /// **المعيار:** WCAG 2.5.5 Level AAA - مساحة نقر لا تقل عن 44x44px
  /// **التطبيق:** نستخدم 48x48px لضمان راحة أكبر
  ///
  /// **الاستخدام:**
  /// ```dart
  /// GestureDetector(
  ///   child: Container(
  ///     width: AppDimensions.minTouchTarget,
  ///     height: AppDimensions.minTouchTarget,
  ///     child: Icon(Icons.close),
  ///   ),
  /// )
  /// ```
  static const double minTouchTarget = 48.0;

  /// مساحة النقر الموصى بها (56px)
  ///
  /// **الاستخدام:** للعناصر الرئيسية والأزرار الأساسية
  static const double recommendedTouchTarget = 56.0;

  // ============================================================================
  // أحجام شريط التطبيق (AppBar Sizes)
  // ============================================================================

  /// ارتفاع شريط التطبيق (56px)
  ///
  /// **الاستخدام:** ارتفاع قياسي لشريط التطبيق
  static const double appBarHeight = 56.0;

  /// ارتفاع شريط التطبيق الكبير (64px)
  ///
  /// **الاستخدام:** شريط تطبيق أكبر للشاشات الرئيسية
  static const double appBarHeightLarge = 64.0;

  // ============================================================================
  // أحجام شريط التنقل السفلي (Bottom Navigation Bar Sizes)
  // ============================================================================

  /// ارتفاع شريط التنقل السفلي (56px)
  ///
  /// **الاستخدام:** ارتفاع قياسي لشريط التنقل
  static const double bottomNavBarHeight = 56.0;

  /// حجم أيقونة شريط التنقل (24px)
  ///
  /// **الاستخدام:** أيقونات شريط التنقل السفلي
  static const double bottomNavBarIconSize = 24.0;

  // ============================================================================
  // أحجام الفواصل (Divider Sizes)
  // ============================================================================

  /// سمك الفاصل (1px)
  ///
  /// **الاستخدام:** فواصل بين العناصر
  static const double dividerThickness = 1.0;

  /// سمك الفاصل السميك (2px)
  ///
  /// **الاستخدام:** فواصل أكثر وضوحاً
  static const double dividerThicknessThick = 2.0;

  // ============================================================================
  // أحجام الشارات (Badge Sizes)
  // ============================================================================

  /// حجم الشارة الصغيرة (16px)
  ///
  /// **الاستخدام:** شارات صغيرة، مؤشرات
  static const double badgeSmall = 16.0;

  /// حجم الشارة المتوسطة (20px)
  ///
  /// **الاستخدام:** شارات عادية
  static const double badgeMedium = 20.0;

  /// حجم الشارة الكبيرة (24px)
  ///
  /// **الاستخدام:** شارات كبيرة، مؤشرات رئيسية
  static const double badgeLarge = 24.0;

  // ============================================================================
  // أحجام الصور الرمزية (Avatar Sizes)
  // ============================================================================

  /// حجم الصورة الرمزية الصغيرة (32px)
  static const double avatarSmall = 32.0;

  /// حجم الصورة الرمزية المتوسطة (48px)
  static const double avatarMedium = 48.0;

  /// حجم الصورة الرمزية الكبيرة (64px)
  static const double avatarLarge = 64.0;

  /// حجم الصورة الرمزية الكبيرة جداً (96px)
  static const double avatarXLarge = 96.0;

  // ============================================================================
  // أحجام مؤشر التحميل (Loading Indicator Sizes)
  // ============================================================================

  /// حجم مؤشر التحميل الصغير (16px)
  static const double loadingIndicatorSmall = 16.0;

  /// حجم مؤشر التحميل المتوسط (24px)
  static const double loadingIndicatorMedium = 24.0;

  /// حجم مؤشر التحميل الكبير (32px)
  static const double loadingIndicatorLarge = 32.0;

  // ============================================================================
  // أحجام الحوارات (Dialog Sizes)
  // ============================================================================

  /// الحد الأقصى لعرض الحوار (400px)
  ///
  /// **الاستخدام:** عرض الحوارات على الشاشات الكبيرة
  static const double dialogMaxWidth = 400.0;

  /// نصف قطر حواف الحوار (16px)
  ///
  /// **الاستخدام:** حواف مستديرة للحوارات
  static const double dialogBorderRadius = 16.0;

  // ============================================================================
  // أحجام Snackbar
  // ============================================================================

  /// ارتفاع Snackbar (48px)
  ///
  /// **الاستخدام:** ارتفاع قياسي للـ snackbar
  static const double snackbarHeight = 48.0;

  /// نصف قطر حواف Snackbar (8px)
  ///
  /// **الاستخدام:** حواف مستديرة للـ snackbar
  static const double snackbarBorderRadius = 8.0;

  // ============================================================================
  // دوال مساعدة (Helper Functions)
  // ============================================================================

  /// يتحقق من أن الحجم المعطى يلبي الحد الأدنى لمساحة النقر
  ///
  /// **المعيار:** WCAG 2.5.5 - مساحة نقر لا تقل عن 44x44px
  ///
  /// **الاستخدام:**
  /// ```dart
  /// final isValid = AppDimensions.isValidTouchTarget(40.0);
  /// // false - أقل من الحد الأدنى
  /// ```
  static bool isValidTouchTarget(double size) {
    return size >= minTouchTarget;
  }

  /// يحسب المسافة بناءً على مضاعف الوحدة الأساسية (8px)
  ///
  /// **الاستخدام:**
  /// ```dart
  /// final spacing = AppDimensions.spacing(3); // 24px
  /// ```
  static double spacing(int multiplier) {
    return spacingSmall * multiplier;
  }

  /// يحسب الحشو بناءً على مضاعف الوحدة الأساسية (8px)
  ///
  /// **الاستخدام:**
  /// ```dart
  /// final padding = AppDimensions.padding(2); // 16px
  /// ```
  static double padding(int multiplier) {
    return paddingSmall * multiplier;
  }
}
