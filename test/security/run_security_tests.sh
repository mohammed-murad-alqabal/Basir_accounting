#!/bin/bash

# =============================================================================
# تشغيل جميع اختبارات الأمان - Security Testing
# =============================================================================
# المشروع: بصير MVP
# التاريخ: 6 ديسمبر 2025
# المؤلف: فريق وكلاء تطوير مشروع بصير
# =============================================================================
# الوصف: تشغيل جميع اختبارات الأمان بشكل شامل
# المتطلبات: Requirements 9.1, 9.2, 9.3, 9.4, 9.5
# =============================================================================

set -e

# تحميل مكتبة معالجة الأخطاء
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/../../scripts/utils/error_handler.sh"

# الألوان
readonly BOLD='\033[1m'

# عدادات
TOTAL_SUITES=0
PASSED_SUITES=0
FAILED_SUITES=0

# =============================================================================
# دوال الاختبار
# =============================================================================

# تشغيل مجموعة اختبارات
run_test_suite() {
    local suite_name=$1
    local suite_script=$2
    
    TOTAL_SUITES=$((TOTAL_SUITES + 1))
    
    print_colored "$CYAN" "\n═══════════════════════════════════════════════════════════"
    print_colored "$CYAN" "  تشغيل: $suite_name"
    print_colored "$CYAN" "═══════════════════════════════════════════════════════════"
    echo ""
    
    if bash "$suite_script"; then
        print_success "\n✓ $suite_name: نجح"
        PASSED_SUITES=$((PASSED_SUITES + 1))
        return 0
    else
        print_error "\n✗ $suite_name: فشل"
        FAILED_SUITES=$((FAILED_SUITES + 1))
        return 1
    fi
}

# =============================================================================
# بدء الاختبارات
# =============================================================================

print_colored "$BLUE" "═══════════════════════════════════════════════════════════"
print_colored "$BLUE" "  اختبارات الأمان الشاملة"
print_colored "$BLUE" "═══════════════════════════════════════════════════════════"
echo ""
print_info "المشروع: بصير MVP"
print_info "التاريخ: $(date '+%Y-%m-%d %H:%M:%S')"
print_info "المتطلبات: 9.1, 9.2, 9.3, 9.4, 9.5"
echo ""

# =============================================================================
# 1. اختبار أنماط الأسرار
# =============================================================================

run_test_suite \
    "اختبار أنماط الأسرار (Requirements 9.2, 9.3)" \
    "$SCRIPT_DIR/test_secret_patterns.sh"

# =============================================================================
# 2. اختبار تنظيف البيانات الحساسة
# =============================================================================

run_test_suite \
    "اختبار تنظيف البيانات الحساسة (Requirements 9.1, 9.5)" \
    "$SCRIPT_DIR/test_sanitization.sh"

# =============================================================================
# 3. اختبار تغطية .gitignore
# =============================================================================

run_test_suite \
    "اختبار تغطية .gitignore (Requirements 9.4)" \
    "$SCRIPT_DIR/test_gitignore_coverage.sh"

# =============================================================================
# النتائج النهائية
# =============================================================================

print_colored "$BLUE" "\n═══════════════════════════════════════════════════════════"
print_colored "$BLUE" "  النتائج النهائية - اختبارات الأمان"
print_colored "$BLUE" "═══════════════════════════════════════════════════════════"
echo ""

echo "إجمالي مجموعات الاختبار: $TOTAL_SUITES"
print_colored "$GREEN" "✓ نجح: $PASSED_SUITES"
print_colored "$RED" "✗ فشل: $FAILED_SUITES"

if [ $TOTAL_SUITES -gt 0 ]; then
    SUCCESS_RATE=$((PASSED_SUITES * 100 / TOTAL_SUITES))
    echo "معدل النجاح: ${SUCCESS_RATE}%"
    
    if [ $SUCCESS_RATE -eq 100 ]; then
        print_colored "$GREEN" "\n🎉 ممتاز! جميع اختبارات الأمان نجحت"
        print_colored "$GREEN" "✓ فحص الأسرار يعمل بشكل ممتاز"
        print_colored "$GREEN" "✓ تنظيف البيانات الحساسة يعمل بشكل ممتاز"
        print_colored "$GREEN" "✓ .gitignore يغطي جميع الملفات الحساسة"
    elif [ $SUCCESS_RATE -ge 70 ]; then
        print_colored "$YELLOW" "\n⚠ جيد، لكن يحتاج بعض التحسين"
    else
        print_colored "$RED" "\n✗ يحتاج إلى تحسينات كبيرة في الأمان"
    fi
fi

echo ""
print_info "تم إكمال جميع اختبارات الأمان"
echo ""

# الخروج
if [ $FAILED_SUITES -gt 0 ]; then
    exit 1
fi

exit 0
