#!/bin/bash

# =============================================================================
# مثال على استخدام مكتبة معالجة الأخطاء
# =============================================================================
# المشروع: بصير MVP
# التاريخ: 6 ديسمبر 2025
# المؤلف: فريق وكلاء تطوير مشروع بصير
# =============================================================================

# تحميل مكتبة معالجة الأخطاء
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/error_handler.sh"

# =============================================================================
# مثال 1: استخدام دوال الطباعة الملونة
# =============================================================================

print_info "بدء تنفيذ السكريبت..."
print_debug "هذه رسالة debug"
print_success "عملية ناجحة!"
print_warning "هذا تحذير"
print_error "هذا خطأ"

# =============================================================================
# مثال 2: التحقق من الأوامر
# =============================================================================

print_info "التحقق من الأوامر المطلوبة..."

if check_command "flutter"; then
    print_success "Flutter متوفر"
else
    log_error "Flutter غير متوفر - يرجى التثبيت"
    exit 1
fi

if check_command "git"; then
    print_success "Git متوفر"
else
    log_warning "Git غير متوفر - بعض الميزات قد لا تعمل"
fi

# =============================================================================
# مثال 3: التحقق من الملفات والمجلدات
# =============================================================================

print_info "التحقق من البنية..."

if check_directory "logs"; then
    print_success "مجلد logs موجود"
else
    log_warning "مجلد logs غير موجود - سيتم إنشاؤه"
    mkdir -p logs || handle_error 1 "فشل إنشاء مجلد logs"
fi

# =============================================================================
# مثال 4: التحقق من المساحة المتوفرة
# =============================================================================

print_info "التحقق من المساحة المتوفرة..."

if check_disk_space 100 "."; then
    print_success "المساحة كافية"
else
    log_warning "المساحة قد تكون غير كافية"
fi

# =============================================================================
# مثال 5: تنفيذ أمر مع معالجة الأخطاء
# =============================================================================

print_info "تنفيذ أمر مع معالجة الأخطاء..."

# محاولة تنفيذ أمر قد يفشل
if flutter --version > /dev/null 2>&1; then
    log_success "تم تنفيذ flutter --version بنجاح"
else
    handle_command_error "flutter --version" $? "فشل تنفيذ الأمر"
fi

# =============================================================================
# مثال 6: إعادة المحاولة التلقائية
# =============================================================================

print_info "مثال على إعادة المحاولة..."

# محاولة تنفيذ أمر مع إعادة المحاولة (3 محاولات، 2 ثانية بين كل محاولة)
if retry_command 3 2 "echo 'اختبار إعادة المحاولة'"; then
    print_success "نجح الأمر"
else
    log_error "فشل الأمر بعد عدة محاولات"
fi

# =============================================================================
# مثال 7: النسخ الاحتياطي والاستعادة
# =============================================================================

print_info "مثال على النسخ الاحتياطي..."

# إنشاء ملف تجريبي
TEST_FILE="test_file.txt"
echo "محتوى تجريبي" > "$TEST_FILE"

# إنشاء نسخة احتياطية
if backup_file "$TEST_FILE" "backups"; then
    print_success "تم إنشاء نسخة احتياطية"
    
    # تعديل الملف الأصلي
    echo "محتوى معدل" > "$TEST_FILE"
    
    # استعادة من النسخة الاحتياطية
    BACKUP_PATH=$(ls -t backups/test_file.txt.backup.* 2>/dev/null | head -1)
    if [ -n "$BACKUP_PATH" ]; then
        if restore_backup "$BACKUP_PATH" "$TEST_FILE"; then
            print_success "تم استعادة النسخة الاحتياطية"
        fi
    fi
fi

# تنظيف
rm -f "$TEST_FILE"
rm -rf backups

# =============================================================================
# مثال 8: معالجة أخطاء الملفات
# =============================================================================

print_info "مثال على معالجة أخطاء الملفات..."

# محاولة قراءة ملف غير موجود
if [ -f "non_existent_file.txt" ]; then
    cat "non_existent_file.txt"
else
    handle_file_error "read" "non_existent_file.txt" "الملف غير موجود"
fi

# =============================================================================
# مثال 9: التنظيف التلقائي
# =============================================================================

print_info "تنظيف الملفات المؤقتة..."
cleanup_temp_files "/tmp" "example_*"

# =============================================================================
# النهاية
# =============================================================================

print_info "انتهى السكريبت بنجاح"
print_error_summary
