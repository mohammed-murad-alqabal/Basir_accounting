while true; do
    show_main_menu
    read -r choice
    
    case $choice in
        1) performance_analysis ;;
        2) test_debugging ;;
        3) code_analysis ;;
        4) device_debugging ;;
        5) database_debugging ;;
        6) network_debugging ;;
        7) system_information ;;
        8) quick_fixes ;;
        9) debug_logs_viewer ;;
        0) 
            print_status "Goodbye! 👋"
            exit 0
            ;;
        *)
            print_error "Invalid choice. Please try again."
            ;;
    esac
    
    echo ""
    echo "Press Enter to continue..."
    read -r
done