        echo ""
        echo "\`\`\`"
        echo "lib/"
        find lib -type f -name "*.dart" | head -20
        echo "..."
        echo "\`\`\`"
        
        echo ""
        echo "## Principles Applied"
        echo ""
        echo "- ✅ COLLABORATION FIRST: Clear documentation structure"
        echo "- ✅ KISS: Simple documentation generation"
        echo "- ✅ Security First: No sensitive information exposed"
        echo "- ✅ Quality First: Comprehensive API documentation"
        echo "- ✅ ENGLISH FOR CODE: All documentation in English"
        
        echo ""
        echo "---"
        echo ""
        echo "**Generated by:** Basir Development Agents Team"
        echo "**Date:** $(date +%Y-%m-%d)"
    } > "$index_file"
    
    print_message "$GREEN" "✅ Documentation index created: $index_file"
}

# Generate final report
generate_report() {
    print_header "📊 Documentation Report"
    
    local report_file="$DOCS_DIR/generation-report.txt"
    
    {
        echo "Documentation Generation Report"
        echo "==============================="
        echo ""
        echo "Date: $(date)"
        echo "Flutter Version: $(flutter --version | head -n 1)"
        echo ""
        echo "Generation Status: ✅ Success"
        echo ""
        echo "Generated Files:"
        
        if [ -d "$HTML_DIR" ]; then
            local html_count=$(find "$HTML_DIR" -name "*.html" | wc -l)
            echo "- HTML files: $html_count"
        fi
        
        if [ -f "$PDF_FILE" ]; then
            local pdf_size_kb=$(du -k "$PDF_FILE" | cut -f1)
            echo "- PDF file: $PDF_FILE (${pdf_size_kb}KB)"
        fi
        
        if [ -d "$DOCS_DIR/coverage" ]; then
            echo "- Coverage report: $DOCS_DIR/coverage/"
        fi
        
        echo ""
        echo "Documentation Location: $DOCS_DIR"
        echo ""
        echo "View Documentation:"
        echo "- Open: $HTML_DIR/index.html"
        
        if [ -f "$PDF_FILE" ]; then
            echo "- Open: $PDF_FILE"
        fi
        
