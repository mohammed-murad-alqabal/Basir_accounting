}

# Main execution
main() {
    print_header "📚 Enhanced Documentation Generator v2.0"
    
    print_message "$BLUE" "Starting documentation generation..."
    echo ""
    
    # Execute generation steps
    pre_generation_checks
    generate_dartdoc
    enhance_html
    generate_pdf
    generate_coverage_docs
    generate_index
    deploy_to_github_pages
    generate_report
    
    print_header "✅ Documentation Generation Completed!"
    
    print_message "$GREEN" "🎉 All steps completed!"
    print_message "$BLUE" "📁 Documentation location: $DOCS_DIR"
    print_message "$BLUE" "🌐 Open: $HTML_DIR/index.html"
}

# Run main function
main "$@"
